// Stermont Arcade - blog writer. Drafts ONE new blog post from the next "pending" topic in blog-topics.json.
// The workflow (.github/workflows/blog-writer.yml) then opens a pull request, so a person reviews the draft
// before anything goes live. It never publishes by itself.
// Needs the repository secret ANTHROPIC_API_KEY. Node 18+, no installs.
import { readFileSync, writeFileSync, existsSync, readdirSync, appendFileSync } from 'node:fs';

const MODEL = process.env.BLOG_MODEL || 'claude-sonnet-5-5';
const KEY = process.env.ANTHROPIC_API_KEY;
const ONLY = (process.env.TOPIC_SLUG || '').trim();
const TOPICS_FILE = 'blog-topics.json';
const out = (k, v) => { if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `${k}=${v}\n`); };
const stop = msg => { console.log(msg); out('written', 'false'); process.exit(0); };
const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const words = s => (String(s).match(/\S+/g) || []).length;

if (!KEY) stop('The ANTHROPIC_API_KEY secret is not set - nothing written.');
if (!existsSync(TOPICS_FILE)) stop('No blog-topics.json - nothing to do.');
const data = JSON.parse(readFileSync(TOPICS_FILE, 'utf8'));
const topic = (data.topics || []).find(t => t.status === 'pending' && (!ONLY || t.slug === ONLY));
if (!topic) stop(ONLY ? `Topic "${ONLY}" is not pending.` : 'No pending topics left in blog-topics.json.');
if (existsSync(`blog/${topic.slug}.html`)) { console.error(`blog/${topic.slug}.html already exists. Change the slug or mark the topic done.`); process.exit(1); }

// Pages the writer may link to: real product pages (not size-redirect pages), existing blog posts and a few fixed pages.
const allowed = new Set(['/products.html', '/c/', '/shipping.html', '/returns.html']);
if (existsSync('p')) for (const f of readdirSync('p').filter(f => f.endsWith('.html')))
  if (!/http-equiv="refresh"/i.test(readFileSync(`p/${f}`, 'utf8'))) allowed.add(`/p/${f}`);
if (existsSync('blog')) for (const f of readdirSync('blog').filter(f => f.endsWith('.html') && f !== 'index.html')) allowed.add(`/blog/${f}`);
const offered = [...new Set([...(topic.links || []), '/products.html', '/blog/how-to-order-and-pay-by-mpesa-online-kenya.html'])].filter(p => allowed.has(p));

const SYSTEM = `You write buying guides and how-to articles for Stermont Arcade, an online store in Kenya (pest control, agrovet, appliances and electronics). Write plain, friendly English for Kenyan shoppers.
Rules:
- Use ONLY the facts supplied in the topic. Do not invent product specifications, ingredients, active ingredients, registration numbers, prices, discounts, stock claims, warranty terms or delivery times.
- Never give chemical dosages, mixing rates, dilution ratios, or animal or human medical dosing. Tell readers to follow the product label and to ask a vet, extension officer or other qualified professional.
- No hype or guarantees (no "best", "guaranteed", "100%", "cure"). Do not name competitors.
- Only include general advice that is widely accepted and safe. If you are unsure of something, leave it out.
- Do not mention AI or that the article was generated.
- 700 to 900 words in total, in short paragraphs.
- Link to store pages only with the exact markup [[/path|anchor text]], using only paths from the allowed list. Use at most 4 links and none in headings.
Reply with ONE JSON object and nothing else (no markdown fences):
{"title": "under 70 characters", "description": "meta description, 70 to 160 characters", "intro": "opening paragraph", "sections": [{"heading": "...", "paragraphs": ["..."]}], "closing": "short closing paragraph"}
Write at least 4 sections.`;

const BAD = [
  [/\b(guarantee[ds]?|100\s?%|cures?|cured)\b/i, 'contains a guarantee or cure claim'],
  [/\bAs an AI\b|\bgenerated by\b/i, 'mentions AI'],
  [/KSh\s?\d|\bKES\s?\d/i, 'contains a price'],
  [/\bPCPB\s*(?:no\.?|reg\w*\.?)?\s*[:#]?\s*\d/i, 'contains a registration number'],
  [/\b\d+(?:\.\d+)?\s?(?:ml|g|kg|l|litres?|liters?)\s?(?:per|\/)\s?(?:litre|liter|l|kg|acre|hectare|tank|knapsack|bird|animal|water)\b/i, 'contains a dosage or mixing rate']
];
function check(a) {
  const p = [];
  if (!a || typeof a !== 'object') return ['not a JSON object'];
  if (typeof a.title !== 'string' || a.title.length < 20 || a.title.length > 70) p.push('title must be 20 to 70 characters');
  if (typeof a.description !== 'string' || a.description.length < 70 || a.description.length > 160) p.push('description must be 70 to 160 characters');
  if (typeof a.intro !== 'string' || !a.intro.trim()) p.push('missing intro');
  if (!Array.isArray(a.sections) || a.sections.length < 4 || a.sections.some(s => !s || typeof s.heading !== 'string' || !Array.isArray(s.paragraphs) || !s.paragraphs.length)) p.push('needs at least 4 sections with a heading and paragraphs');
  const all = [a.title, a.description, a.intro, a.closing, ...(a.sections || []).flatMap(s => [s.heading, ...(s.paragraphs || [])])].filter(x => typeof x === 'string').join('\n');
  if (words(all) < 500) p.push('too short (under 500 words)');
  if ((all.match(/\[\[/g) || []).length > 6) p.push('too many links');
  for (const [re, why] of BAD) if (re.test(all)) p.push(why);
  return p;
}

async function ask(extra) {
  const user = `Topic: ${topic.title}\nAngle: ${topic.angle || ''}\nKeywords to work in naturally: ${(topic.keywords || []).join(', ')}\nFacts you may use (nothing else about our products):\n${(topic.facts || []).map(f => '- ' + f).join('\n')}\nAllowed link paths:\n${offered.map(p => '- ' + p).join('\n')}${extra ? `\n\nYour previous attempt was rejected because: ${extra}. Fix this.` : ''}`;
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST', headers: { 'x-api-key': KEY, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
    body: JSON.stringify({ model: MODEL, max_tokens: 4000, system: SYSTEM, messages: [{ role: 'user', content: user }] })
  });
  if (!res.ok) throw new Error(`Anthropic API error ${res.status}: ${(await res.text()).slice(0, 300)}`);
  const j = await res.json();
  const text = (j.content || []).filter(b => b.type === 'text').map(b => b.text).join('');
  const a = text.indexOf('{'), b = text.lastIndexOf('}');
  try { return JSON.parse(text.slice(a, b + 1)); } catch { return null; }
}

let art = null, problems = [];
for (let i = 0; i < 2; i++) {
  art = await ask(problems.join('; '));
  problems = check(art);
  if (!problems.length) break;
  console.log(`Attempt ${i + 1} rejected: ${problems.join('; ')}`);
}
if (problems.length) { console.error('Could not produce a draft that passes the checks. Nothing written.'); process.exit(1); }

const SITE = 'https://stermontarcade.co.ke';
const para = s => '<p>' + esc(s).replace(/\[\[(\/[^|\]]+)\|([^\]]+)\]\]/g, (m, path, text) => allowed.has(path) ? `<a href="${path}">${text}</a>` : text).replace(/\[\[|\]\]/g, '') + '</p>';
const plain = s => String(s).replace(/\[\[\/[^|\]]+\|([^\]]+)\]\]/g, '$1');
const total = words([art.title, art.intro, art.closing, ...art.sections.flatMap(s => [s.heading, ...s.paragraphs])].filter(Boolean).map(plain).join(' '));
const now = new Date(), iso = now.toISOString().slice(0, 10);
const nice = now.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
const url = `${SITE}/blog/${topic.slug}.html`;
const ld = o => '<script type="application/ld+json">' + JSON.stringify(o).replace(/</g, '\\u003c') + '</script>';
const CSS = '*{box-sizing:border-box}body{margin:0;font:16px/1.6 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:#1f1b2e;background:#faf9fd}a{color:#6d28d9}header{background:#7c3aed;color:#fff;padding:.8rem 1rem}header a{color:#fff;text-decoration:none;font-weight:800;font-size:1.15rem}main{max-width:760px;margin:0 auto;padding:1rem}nav.bc{font-size:.85rem;color:#6b6b80;margin:.3rem 0 1rem}h1{font-size:1.6rem;line-height:1.25;margin:.2rem 0 .6rem}h2{font-size:1.25rem;margin:1.6rem 0 .4rem}.btn{display:block;text-align:center;background:#16a34a;color:#fff;text-decoration:none;font-weight:800;padding:.85rem;border-radius:12px;margin:1rem 0}.box{background:#fff;border:1px solid #e6e1f5;border-radius:14px;padding:.9rem 1rem;margin:1rem 0}.meta{color:#6b6b80;font-size:.85rem}footer{max-width:760px;margin:2rem auto;padding:1rem;color:#6b6b80;font-size:.85rem;border-top:1px solid #e6e1f5}';
const html = `<!doctype html>
<html lang="en-KE"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(art.title)} | Stermont Arcade</title><meta name="description" content="${esc(art.description)}">
<link rel="canonical" href="${url}"><meta name="robots" content="index, follow, max-image-preview:large">
<meta property="og:type" content="article"><meta property="og:site_name" content="Stermont Arcade"><meta property="og:locale" content="en_KE">
<meta property="og:title" content="${esc(art.title)}"><meta property="og:description" content="${esc(art.description)}"><meta property="og:url" content="${url}">
<meta property="og:image" content="${SITE}/logo.png"><meta name="twitter:card" content="summary_large_image"><meta name="theme-color" content="#7c3aed">
<style>${CSS}</style>
${ld({ '@context': 'https://schema.org', '@type': 'Article', headline: art.title, datePublished: iso, dateModified: iso, inLanguage: 'en-KE', author: { '@type': 'Organization', name: 'Stermont Arcade' }, publisher: { '@type': 'Organization', name: 'Stermont Arcade', logo: { '@type': 'ImageObject', url: `${SITE}/logo.png` } }, mainEntityOfPage: url, image: `${SITE}/logo.png` })}
${ld({ '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [['Home', `${SITE}/`], ['Buying guides', `${SITE}/blog/`], [art.title, url]].map(([name, item], i) => ({ '@type': 'ListItem', position: i + 1, name, item })) })}
<script src="/analytics.js" defer></script></head><body>
<header><a href="${SITE}/">Stermont Arcade</a></header><main>
<nav class="bc"><a href="${SITE}/">Home</a> › <a href="/blog/">Buying guides</a> › ${esc(art.title)}</nav>
<h1>${esc(art.title)}</h1>
<p class="meta">Updated ${nice} · ${Math.max(2, Math.round(total / 200))} min read</p>
${para(art.intro)}
${art.sections.map(s => `<h2>${esc(s.heading)}</h2>\n${s.paragraphs.map(para).join('\n')}`).join('\n')}
${art.closing ? para(art.closing) : ''}
<a class="btn" href="/products.html">Browse all products</a>
<div class="box"><a href="https://wa.me/254748888230?text=Hello%20Stermont%20Arcade">Questions? Chat with us on WhatsApp</a></div>
</main>
<footer>Stermont Arcade · Online store serving all of Kenya · Pay by M-Pesa · Delivery to all 47 counties · <a href="https://wa.me/254748888230">WhatsApp +254 748 888 230</a> · <a href="/shipping.html">Shipping</a> · <a href="/returns.html">Returns</a> · <a href="/privacy.html">Privacy</a></footer><script src="/analytics.js" defer></script></body></html>
`;
writeFileSync(`blog/${topic.slug}.html`, html);
topic.status = 'drafted'; topic.drafted = iso;
writeFileSync(TOPICS_FILE, JSON.stringify(data, null, 2) + '\n');
console.log(`Wrote blog/${topic.slug}.html (${total} words).`);
out('written', 'true'); out('slug', topic.slug); out('title', art.title.replace(/[\r\n]/g, ' '));
