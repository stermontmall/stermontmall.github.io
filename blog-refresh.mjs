// Stermont Arcade - blog refresher. Once a week it picks the ONE published post that has gone longest without an update
// (older than REFRESH_DAYS, default 90), then:
//  1. removes links that no longer work (a broken button is pointed at /products.html instead),
//  2. adds 2-3 new FAQ answers (also written into the FAQPage schema) using only facts already in the article,
//  3. sets "Updated" and dateModified to today - but ONLY if something really changed, so freshness signals stay honest.
// The workflow opens a pull request with a checklist for the things a bot cannot do (fresh photos or a short video, price and stock checks).
// A post with nothing to change is logged in blog-refresh-log.json so the next run moves on to the next stale post.
// Needs ANTHROPIC_API_KEY for the FAQ step (the link check works without it). Node 18+, no installs.
import { readFileSync, writeFileSync, existsSync, readdirSync, appendFileSync } from 'node:fs';

const KEY = process.env.ANTHROPIC_API_KEY;
const MODEL = process.env.BLOG_MODEL || 'claude-sonnet-5-5';
const DAYS = Number(process.env.REFRESH_DAYS || 90);
const ONLY = (process.env.POST_SLUG || '').trim();
const LOG = 'blog-refresh-log.json', NOTES = 'refresh-notes.md';
const out = (k, v) => { if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `${k}=${v}\n`); };
const stop = msg => { console.log(msg); out('written', 'false'); out('logged', 'false'); process.exit(0); };
const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const words = s => (String(s).match(/\S+/g) || []).length;
const today = new Date().toISOString().slice(0, 10);
const nice = new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
const daysAgo = d => d ? Math.floor((Date.parse(today) - Date.parse(d)) / 864e5) : 9999;
const ld = o => '<script type="application/ld+json">' + JSON.stringify(o).replace(/</g, '\\u003c') + '</script>';

if (!ONLY && existsSync('open-refreshes.txt') && readFileSync('open-refreshes.txt', 'utf8').trim()) stop('A refresh pull request is still waiting for review - not opening another.');
if (!existsSync('blog')) stop('No blog folder - nothing to do.');
const log = existsSync(LOG) ? JSON.parse(readFileSync(LOG, 'utf8')) : {};

// ---- pick the stalest post ----
const cands = [];
for (const f of readdirSync('blog').filter(f => f.endsWith('.html') && f !== 'index.html')) {
  const slug = f.replace(/\.html$/, '');
  if (ONLY && slug !== ONLY) continue;
  const h = readFileSync(`blog/${f}`, 'utf8');
  if (/<meta name=["']robots["'] content=["'][^"']*noindex/i.test(h)) continue;
  const mod = (h.match(/"dateModified":"(\d{4}-\d{2}-\d{2})/) || [])[1] || (h.match(/"datePublished":"(\d{4}-\d{2}-\d{2})/) || [])[1] || '';
  const last = [mod, log[slug]].filter(Boolean).sort().pop() || '';
  const age = daysAgo(last);
  if (ONLY || age >= DAYS) cands.push({ slug, h, age });
}
cands.sort((a, b) => b.age - a.age);
const pick = cands[0];
if (!pick) stop(`No post is older than ${DAYS} days - nothing to refresh.`);
console.log(`Reviewing blog/${pick.slug}.html (${pick.age} days since last update).`);
let html = pick.h;

// ---- 1. link check ----
const exists = path => {
  const p = path.split('#')[0].split('?')[0];
  const file = p === '/' ? 'index.html' : p.endsWith('/') ? p.slice(1) + 'index.html' : p.slice(1);
  if (!existsSync(file)) return false;
  return !(file.endsWith('.html') && /http-equiv="refresh"/i.test(readFileSync(file, 'utf8')));
};
const broken = [];
html = html.replace(/<a ([^>]*?)href="(\/[^"#?]*)([^"]*)"([^>]*)>([\s\S]*?)<\/a>/g, (m, pre, path, rest, post, text) => {
  if (path.startsWith('//') || exists(path)) return m;
  broken.push(path);
  return /class="[^"]*\bbtn\b/.test(pre + post) ? `<a ${pre}href="/products.html"${post}>${text}</a>` : text;
});

// ---- 2. new FAQs ----
const ldBlocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
let faqs = [], faqLd = null;
for (const m of ldBlocks) {
  try { const o = JSON.parse(m[1]); if (o['@type'] === 'FAQPage') { faqLd = m[0]; faqs = (o.mainEntity || []).map(q => ({ q: q.name, a: (q.acceptedAnswer || {}).text || '' })); } } catch { /* ignore */ }
}
const hasMarkers = html.includes('<!--FAQ-START-->');
const foreignFaq = !hasMarkers && !faqLd && /frequently asked questions|<h2[^>]*>\s*FAQ/i.test(html);
const bodyText = ((html.match(/<main[\s\S]*?<\/main>/i) || [html])[0]).replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/\s+/g, ' ').trim().slice(0, 14000);
const BAD = [
  [/\b(guarantee[ds]?|100\s?%|cures?|cured)\b/i, 'contains a guarantee or cure claim'],
  [/\bAs an AI\b|\bgenerated by\b/i, 'mentions AI'],
  [/KSh\s?\d|\bKES\s?\d/i, 'contains a price'],
  [/\b\d+(?:\.\d+)?\s?(?:ml|g|kg|l|litres?|liters?)\s?(?:per|\/)\s?(?:litre|liter|l|kg|acre|hectare|tank|knapsack|bird|animal|water)\b/i, 'contains a dosage or mixing rate'],
  [/\[\[|https?:\/\//i, 'contains a link']
];
function checkFaqs(a) {
  if (!a || !Array.isArray(a.faqs) || a.faqs.length < 1 || a.faqs.length > 3) return ['reply needs 1 to 3 faqs'];
  const p = [];
  for (const f of a.faqs) {
    if (!f || typeof f.q !== 'string' || typeof f.a !== 'string' || !f.q.trim().endsWith('?')) { p.push('each faq needs a question ending in ? and an answer'); continue; }
    const n = words(f.a);
    if (n < 20 || n > 80) p.push('answers must be 25 to 70 words');
    const t = f.q + ' ' + f.a;
    for (const [re, why] of BAD) if (re.test(t)) p.push(why);
    for (const m of t.matchAll(/\bPCPB\s*(?:no\.?|reg\w*\.?)?\s*[:#]?\s*(\d[\d\/-]*)/gi)) if (!bodyText.includes(m[1])) p.push('contains a PCPB number that is not in the article');
    if (faqs.some(e => e.q.trim().toLowerCase() === f.q.trim().toLowerCase())) p.push('repeats an existing question');
  }
  return [...new Set(p)];
}
async function askFaqs(extra) {
  const system = `You review a published article from Stermont Arcade, an online store in Kenya, and write NEW frequently asked questions that real Kenyan shoppers would ask next. Use ONLY facts already stated in the article text. Do not add product facts, prices, registration numbers, dosages, mixing rates, guarantees, links or competitor names, and never mention AI. Never give chemical dosing or mixing advice: tell readers to follow the label and ask a qualified professional. Each answer is 25 to 70 words of plain English. Do not repeat these existing questions: ${faqs.map(f => f.q).join(' | ') || '(none)'}.\nReply with ONE JSON object and nothing else: {"faqs": [{"q": "...?", "a": "..."}]} with 2 or 3 items.`;
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST', headers: { 'x-api-key': KEY, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
    body: JSON.stringify({ model: MODEL, max_tokens: 1500, system, messages: [{ role: 'user', content: `Article text:\n${bodyText}${extra ? `\n\nYour previous attempt was rejected because: ${extra}. Fix this.` : ''}` }] })
  });
  if (!res.ok) throw new Error(`Anthropic API error ${res.status}: ${(await res.text()).slice(0, 300)}`);
  const j = await res.json();
  const text = (j.content || []).filter(b => b.type === 'text').map(b => b.text).join('');
  const a = text.indexOf('{'), b = text.lastIndexOf('}');
  try { return JSON.parse(text.slice(a, b + 1)); } catch { return null; }
}
const added = [];
if (!KEY) console.log('ANTHROPIC_API_KEY is not set - skipping the FAQ step.');
else if (foreignFaq) console.log('This post already has a hand-written FAQ - skipping the FAQ step.');
else if (faqs.length >= 8) console.log('This post already has 8 FAQs - skipping the FAQ step.');
else {
  let res = null, problems = [];
  for (let i = 0; i < 2; i++) {
    res = await askFaqs(problems.join('; '));
    problems = checkFaqs(res);
    if (!problems.length) break;
    console.log(`FAQ attempt ${i + 1} rejected: ${problems.join('; ')}`);
  }
  if (!problems.length) {
    for (const f of res.faqs) added.push({ q: f.q.trim(), a: f.a.trim() });
    faqs = [...faqs, ...added].slice(0, 8);
    const block = `<!--FAQ-START-->\n<section id="faq"><h2>Frequently asked questions</h2>\n${faqs.map(f => `<h3>${esc(f.q)}</h3>\n<p>${esc(f.a)}</p>`).join('\n')}\n</section>\n<!--FAQ-END-->`;
    if (hasMarkers) html = html.replace(/<!--FAQ-START-->[\s\S]*?<!--FAQ-END-->/, () => block);
    else if (/<a class="btn"/.test(html)) html = html.replace(/<a class="btn"/, () => block + '\n<a class="btn"');
    else html = html.replace('</main>', () => block + '\n</main>');
    const faqScript = ld({ '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: faqs.map(f => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })) });
    if (faqLd) html = html.replace(faqLd, () => faqScript);
    else html = html.replace('</head>', () => faqScript + '\n</head>');
  } else console.log('Could not get FAQs that pass the checks - skipping the FAQ step.');
}

// ---- 3. only touch the dates if something really changed ----
if (!broken.length && !added.length) {
  log[pick.slug] = today;
  writeFileSync(LOG, JSON.stringify(log, null, 2) + '\n');
  console.log('Nothing needed changing - logged as reviewed.');
  out('written', 'false'); out('logged', 'true');
  process.exit(0);
}
const hadModified = /"dateModified":"\d{4}-\d{2}-\d{2}/.test(html);
html = html.replace(/("dateModified":")\d{4}-\d{2}-\d{2}/g, `$1${today}`);
html = html.replace(/(<p class="meta">)Updated [^·<]*/, `$1Updated ${nice} `);
writeFileSync(`blog/${pick.slug}.html`, html);
log[pick.slug] = today;
writeFileSync(LOG, JSON.stringify(log, null, 2) + '\n');
const h1 = ((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i) || [])[1] || pick.slug).replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const notes = [
  `Automatic refresh of /blog/${pick.slug}.html (${pick.age} days since its last update).`,
  '',
  '## What changed',
  broken.length ? `- Fixed ${broken.length} broken link(s): ${[...new Set(broken)].join(', ')}` : '- No broken links found.',
  added.length ? `- Added ${added.length} new FAQ(s), also written into the FAQ schema:\n${added.map(f => `  - ${f.q}`).join('\n')}` : '- No new FAQs added.',
  `- "Updated" date and dateModified set to ${today}${hadModified ? '' : ' (this older post has no dateModified field, so the sitemap date will not change)'}.`,
  '',
  '## Please check before merging (a bot cannot do these)',
  '- [ ] Add or replace a photo, or add a short how-to video, of the featured product in use.',
  '- [ ] Open each linked product page: is the product still in stock and is the price shown there current? (Blog posts do not hard-code prices, so they never go stale.)',
  '- [ ] Add any new customer questions from WhatsApp as FAQs.',
  '',
  'Merging updates the sitemap date automatically. Close the PR to discard.'
].join('\n');
writeFileSync(NOTES, notes + '\n');
console.log(`Refreshed blog/${pick.slug}.html: ${broken.length} link fix(es), ${added.length} new FAQ(s).`);
out('written', 'true'); out('logged', 'false'); out('slug', pick.slug); out('title', h1.replace(/[\r\n]/g, ' '));
